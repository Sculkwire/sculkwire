/** Regolith projects through the validator: what rgl last built in `.regolith/tmp` (no rgl runs here). */
import { cpSync, lstatSync, lutimesSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, symlinkSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, relative } from "node:path";
import { afterAll, describe, expect, it } from "vitest";
import { type ValidationResult, validateProject } from "./index.ts";

const tmp = mkdtempSync(join(tmpdir(), "sculk-validate-rgl-"));
afterAll(() => rmSync(tmp, { recursive: true, force: true }));

const CHANGED = "[changed by Regolith filters; position refers to the build output]";
const GENERATED = "[generated by Regolith filters; position refers to the build output]";
/** A junction needs no privilege on Windows, and rgl's links read the same way through it. */
const LINK = process.platform === "win32" ? "junction" : "dir";

/** A Regolith project whose default profile runs a filter; the entity has a trailing comma (a warning) on line 2. */
function project(name: string): string {
  const root = join(tmp, name);
  const manifest = (kind: "data" | "resources", n: number) => ({
    format_version: 2,
    header: { name: "Steve", description: "", uuid: `0000000${n}-0000-4000-8000-000000000001`, version: [1, 0, 0], min_engine_version: [1, 21, 0] },
    modules: [{ type: kind, uuid: `0000000${n}-0000-4000-8000-000000000002`, version: [1, 0, 0] }],
  });
  mkdirSync(join(root, "packs", "BP", "entities"), { recursive: true });
  mkdirSync(join(root, "packs", "RP"), { recursive: true });
  mkdirSync(join(root, "data"), { recursive: true });
  writeFileSync(join(root, "packs", "BP", "manifest.json"), JSON.stringify(manifest("data", 1)));
  writeFileSync(join(root, "packs", "RP", "manifest.json"), JSON.stringify(manifest("resources", 2)));
  writeFileSync(join(root, "packs", "BP", "entities", "mob.json"), '{\n  "format_version": "1.21.0",\n}\n');
  writeFileSync(
    join(root, "config.json"),
    JSON.stringify({ name: "steve", packs: { behaviorPack: "./packs/BP", resourcePack: "./packs/RP" }, regolith: { dataPath: "./data", profiles: { default: { filters: [{ filter: "x" }] } } } }),
  );
  return root;
}

/** What a filter run leaves: the source packs, one line prepended to the entity and one generated file. */
function writeOutput(root: string, bp: string, rp: string): void {
  cpSync(join(root, "packs", "BP"), bp, { recursive: true });
  cpSync(join(root, "packs", "RP"), rp, { recursive: true });
  const entity = join(bp, "entities", "mob.json");
  writeFileSync(entity, `// added by a filter\n${readFileSync(entity, "utf8")}`);
  writeFileSync(join(bp, "entities", "made.json"), '{\n  "format_version": "1.21.0",\n}\n');
}

/** Every file under a dir with its content, to prove nothing was written, moved or deleted. */
function snapshot(dir: string): Record<string, string> {
  const out: Record<string, string> = {};
  for (const e of readdirSync(dir, { recursive: true, withFileTypes: true })) {
    if (e.isFile()) out[relative(dir, join(e.parentPath, e.name))] = readFileSync(join(e.parentPath, e.name), "utf8");
  }
  return out;
}

const commas = (r: ValidationResult) => r.diagnostics.filter((d) => d.code === "json.trailing-comma");

describe("validate_pack on a Regolith project", () => {
  it("validates rgl's output in .regolith/tmp under the source paths, noting changed and generated files", async () => {
    const root = project("folder");
    writeOutput(root, join(root, ".regolith", "tmp", "BP"), join(root, ".regolith", "tmp", "RP"));
    const r = await validateProject(root, { checks: ["json"] });
    expect(r.regolith).toMatchObject({ profile: "default", built: true, message: expect.stringContaining("rgl run") });
    expect(r.regolith?.builtAt).toBeUndefined();
    expect(r.packs.map((p) => p.relDir)).toEqual(["packs/BP", "packs/RP"]);
    const [made, mob] = commas(r).sort((a, b) => (a.file ?? "").localeCompare(b.file ?? ""));
    expect(mob).toMatchObject({ file: "packs/BP/entities/mob.json", range: { start: { line: 3 } } });
    expect(mob?.message).toContain(CHANGED);
    expect(made).toMatchObject({ file: "packs/BP/entities/made.json", range: { start: { line: 2 } } });
    expect(made?.message).toContain(GENERATED);
    expect(r.diagnostics.find((d) => d.code.startsWith("regolith."))).toBeUndefined();
  });

  it("follows .regolith/tmp links to the export folder, reports when rgl ran and leaves the output untouched", async () => {
    const root = project("linked");
    const exported = join(tmp, "linked-export");
    writeOutput(root, join(exported, "steve_bp"), join(exported, "steve_rp"));
    const linkDir = join(root, ".regolith", "tmp");
    mkdirSync(linkDir, { recursive: true });
    symlinkSync(join(exported, "steve_bp"), join(linkDir, "BP"), LINK);
    symlinkSync(join(exported, "steve_rp"), join(linkDir, "RP"), LINK);
    const ranAt = new Date("2026-01-02T03:04:05.000Z");
    lutimesSync(join(linkDir, "BP"), ranAt, ranAt);
    lutimesSync(join(linkDir, "RP"), ranAt, ranAt);
    const before = snapshot(exported);

    const r = await validateProject(root, { checks: ["json"] });
    expect(r.regolith).toMatchObject({ profile: "default", built: true, builtAt: ranAt.toISOString() });
    expect(r.regolith?.message).toContain(ranAt.toISOString());
    expect(commas(r).find((d) => d.file === "packs/BP/entities/mob.json")?.message).toContain(CHANGED);

    expect(lstatSync(join(linkDir, "BP")).isSymbolicLink()).toBe(true);
    expect(lstatSync(join(linkDir, "RP")).isSymbolicLink()).toBe(true);
    expect(snapshot(exported)).toEqual(before);
  });

  it("says which pack rgl's output lacks, and validates that one from its source", async () => {
    for (const [mode, severity] of [
      ["auto", "warning"],
      ["build", "error"],
    ] as const) {
      const root = project(`partial-${mode}`);
      writeOutput(root, join(root, ".regolith", "tmp", "BP"), join(root, ".regolith", "tmp", "RP"));
      rmSync(join(root, ".regolith", "tmp", "RP"), { recursive: true });
      const r = await validateProject(root, { checks: ["json"], regolith: mode });
      expect(r.regolith).toMatchObject({ built: true });
      const d = r.diagnostics.find((x) => x.code === "regolith.not-built");
      expect(d).toMatchObject({ severity, file: "config.json" });
      expect(d?.message).toContain("packs/RP");
      expect(d?.message).not.toContain("packs/BP");
      expect(r.ok).toBe(mode === "auto");
      // The behavior pack is still rgl's output.
      expect(commas(r).find((x) => x.file === "packs/BP/entities/mob.json")?.message).toContain(CHANGED);
    }
  });

  it("does not ask rgl for a pack config.json does not name", async () => {
    const root = project("extra");
    writeOutput(root, join(root, ".regolith", "tmp", "BP"), join(root, ".regolith", "tmp", "RP"));
    cpSync(join(root, "packs", "BP"), join(root, "examples", "BP"), { recursive: true });
    const r = await validateProject(root, { checks: ["json"], regolith: "build" });
    expect(r.packs.map((p) => p.relDir)).toEqual(["examples/BP", "packs/BP", "packs/RP"]);
    expect(r.diagnostics.find((d) => d.code === "regolith.not-built")).toBeUndefined();
  });

  it("validates the source packs with a warning when rgl has not built the project", async () => {
    const r = await validateProject(project("unbuilt"), { checks: ["json"] });
    expect(r.regolith).toMatchObject({ profile: "default", built: false, message: expect.stringContaining("rgl has not built this project") });
    expect(r.diagnostics.find((d) => d.code === "regolith.not-built")).toMatchObject({ severity: "warning", source: "manifest", file: "config.json" });
    expect(commas(r)).toEqual([expect.objectContaining({ file: "packs/BP/entities/mob.json", range: expect.objectContaining({ start: expect.objectContaining({ line: 2 }) }) })]);
    expect(commas(r)[0]?.message).not.toContain("Regolith filters");
    expect(r.ok).toBe(true);
  });

  it("fails with an error when regolith: build finds no output", async () => {
    const r = await validateProject(project("required"), { checks: ["json"], regolith: "build" });
    expect(r.regolith).toMatchObject({ built: false });
    expect(r.diagnostics.find((d) => d.code === "regolith.not-built")).toMatchObject({ severity: "error", file: "config.json" });
    expect(commas(r).map((d) => d.file)).toEqual(["packs/BP/entities/mob.json"]);
    expect(r.ok).toBe(false);
  });

  it("validates the source packs with an info when regolith: source skips the output", async () => {
    const root = project("source");
    writeOutput(root, join(root, ".regolith", "tmp", "BP"), join(root, ".regolith", "tmp", "RP"));
    const r = await validateProject(root, { checks: ["json"], regolith: "source" });
    expect(r.regolith).toMatchObject({ profile: "default", built: false });
    expect(r.diagnostics.find((d) => d.code === "regolith.not-built")).toMatchObject({ severity: "info", file: "config.json" });
    expect(commas(r)).toHaveLength(1);
    expect(commas(r)[0]).toMatchObject({ file: "packs/BP/entities/mob.json", range: { start: { line: 2 } } });
  });
});
